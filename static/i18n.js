let currentLang = 'en';

function normalizeLangCode(raw) {
    if (!raw || typeof raw !== 'string') return 'en';
    const base = raw.trim().toLowerCase().split(/[-_]/)[0];
    if (base === 'iw') return 'he';
    return Object.prototype.hasOwnProperty.call(TRANSLATIONS, base) ? base : 'en';
}

function detectSystemLanguage(serverLang) {
    if (serverLang) return normalizeLangCode(serverLang);
    const navList = (navigator.languages && navigator.languages.length)
        ? navigator.languages
        : [navigator.language || navigator.userLanguage || 'en'];
    for (let i = 0; i < navList.length; i++) {
        const code = normalizeLangCode(navList[i]);
        if (code !== 'en' || (navList[i] || '').toLowerCase().startsWith('en')) return code;
    }
    return 'en';
}

function t(key, vars) {
    const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
    let str = dict[key] !== undefined ? dict[key] : (TRANSLATIONS.en[key] !== undefined ? TRANSLATIONS.en[key] : key);
    if (vars && typeof vars === 'object') {
        Object.keys(vars).forEach((k) => {
            str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(vars[k]));
        });
    }
    return str;
}

function renderLangMenu() {
    const menu = document.getElementById('lang-menu');
    if (!menu) return;
    menu.innerHTML = `<div class="theme-menu-title">${t('header.lang_menu')}</div>`;
    LANGUAGES.forEach((l) => {
        const btn = document.createElement('button');
        btn.type = 'button';
        btn.className = 'theme-option' + (l.id === currentLang ? ' active' : '');
        btn.innerHTML = `
            <span class="lang-badge">${l.badge}</span>
            <span class="theme-name">${l.name}</span>
            <span class="theme-check"></span>`;
        btn.addEventListener('click', () => {
            applyLanguage(l.id, true);
            const picker = document.getElementById('lang-picker');
            if (picker) picker.classList.remove('open');
        });
        menu.appendChild(btn);
    });
}

function applyLanguage(langCode, persist = true) {
    const next = normalizeLangCode(langCode);
    currentLang = next;
    const meta = LANGUAGES.find((l) => l.id === next) || LANGUAGES[0];
    document.documentElement.lang = next;
    document.documentElement.dir = meta.dir || 'ltr';

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
        el.innerHTML = t(el.dataset.i18nHtml);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
        el.title = t(el.dataset.i18nTitle);
    });

    renderLangMenu();
    if (typeof renderThemeMenu === 'function') renderThemeMenu();
    if (typeof updateDynamicTranslations === 'function') updateDynamicTranslations();

    if (persist) {
        try { localStorage.setItem('soundx_lang', next); } catch (e) { }
        fetch('/api/config/save', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ language: next })
        }).catch(() => { });
    }
}

function initLangPicker() {
    const picker = document.getElementById('lang-picker');
    const btn = document.getElementById('lang-btn');
    if (!picker || !btn) return;
    renderLangMenu();
    btn.addEventListener('click', (e) => {
        e.stopPropagation();
        const tp = document.getElementById('theme-picker');
        if (tp) tp.classList.remove('open');
        picker.classList.toggle('open');
    });
    document.addEventListener('click', (e) => {
        if (!picker.contains(e.target)) picker.classList.remove('open');
    });
}
